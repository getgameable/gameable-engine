#!/usr/bin/env node
/**
 * Regenerate the ambient TypeScript declarations for the `gameable:engine` WIT
 * imports into `packages/sdk/src/wit/generated/`.
 *
 * `packages/sdk/src/wit/entry.ts` imports `'gameable:engine/env@0.2.0'` and friends.
 * Those specifiers only exist inside `jco componentize`; `jco guest-types`
 * emits the `declare module` blocks that let `tsc` and ESLint resolve them.
 *
 * The output is committed so a fresh clone typechecks without running jco.
 *
 * Usage:
 *   node scripts/gen-wit-types.mjs           regenerate in place
 *   node scripts/gen-wit-types.mjs --check   regenerate to a temp dir and diff
 *
 * Every path handed to jco is absolute and forward-slashed, because Windows
 * paths break shell-string pipelines.
 */
import { spawnSync } from 'node:child_process';
import * as prettier from 'prettier';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Absolute, forward-slashed path to `packages/sdk`. */
const PKG = fileURLToPath(new URL('../', import.meta.url))
  .replaceAll('\\', '/')
  .replace(/\/$/, '');
/** Absolute, forward-slashed path to the repository root. */
const ROOT = dirname(dirname(PKG)).replaceAll('\\', '/');
/** The authored WIT package. */
const WIT = `${ROOT}/wit`;
/** Where the committed declarations live. */
const OUT = `${PKG}/src/wit/generated`;
/** The jco entry point, resolved from the repository's own install. */
const JCO = `${ROOT}/node_modules/@bytecodealliance/jco/dist/jco.js`;

/** Header prepended to every generated file. */
const BANNER = [
  '/* eslint-disable */',
  '// GENERATED by packages/sdk/scripts/gen-wit-types.mjs — do not edit.',
  '// Run `npm run gen:wit -w packages/sdk` after changing wit/*.wit.',
  '',
].join('\n');

/**
 * Run `jco guest-types` into `dir`.
 *
 * The output is run through Prettier with the repository's own configuration,
 * so `--check` stays stable no matter what formats the repository afterwards.
 *
 * @param {string} dir Absolute, forward-slashed output directory.
 * @returns {Promise<void>}
 */
async function generate(dir) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const result = spawnSync(
    process.execPath,
    [JCO, 'guest-types', WIT, '--world-name', 'game-module', '--name', 'wit', '-o', dir, '--quiet'],
    { stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? '');
    process.stderr.write(result.stderr ?? '');
    throw new Error(`jco guest-types failed with status ${String(result.status)}`);
  }
  const options = (await prettier.resolveConfig(`${OUT}/wit.d.ts`)) ?? {};
  for (const file of walk(dir)) {
    const text = readFileSync(file, 'utf8');
    const formatted = await prettier.format(`${BANNER}${text.replace(/\r\n/g, '\n')}`, {
      ...options,
      parser: 'typescript',
    });
    writeFileSync(file, formatted, 'utf8');
  }
}

/**
 * Every file under `dir`, recursively.
 *
 * @param {string} dir Absolute directory.
 * @returns {string[]} Absolute file paths, sorted.
 */
function walk(dir) {
  /** @type {string[]} */
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name < b.name ? -1 : 1,
  )) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

/**
 * Repo-relative paths and contents of every file under `dir`.
 *
 * @param {string} dir Absolute directory.
 * @returns {Map<string, string>} Relative path to contents.
 */
function snapshot(dir) {
  const map = new Map();
  if (!existsSync(dir)) return map;
  for (const file of walk(dir)) {
    map.set(file.slice(dir.length + 1).replaceAll('\\', '/'), readFileSync(file, 'utf8'));
  }
  return map;
}

const check = process.argv.includes('--check');

if (check) {
  const tmp = mkdtempSync(join(tmpdir(), 'aos-wit-types-')).replaceAll('\\', '/');
  try {
    await generate(tmp);
    const fresh = snapshot(tmp);
    const committed = snapshot(OUT);
    /** @type {string[]} */
    const problems = [];
    for (const [name, text] of fresh) {
      if (!committed.has(name)) problems.push(`missing: ${name}`);
      else if (committed.get(name) !== text) problems.push(`stale: ${name}`);
    }
    for (const name of committed.keys()) {
      if (!fresh.has(name)) problems.push(`unexpected: ${name}`);
    }
    if (problems.length > 0) {
      console.error('packages/sdk/src/wit/generated is out of date:');
      for (const p of problems) console.error(`  - ${p}`);
      console.error('Run `npm run gen:wit -w packages/sdk` and commit the result.');
      process.exit(1);
    }
    console.log(`wit types ok — ${String(committed.size)} files match wit/`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
} else {
  const tmp = mkdtempSync(join(tmpdir(), 'aos-wit-types-')).replaceAll('\\', '/');
  try {
    await generate(tmp);
    rmSync(OUT, { recursive: true, force: true });
    mkdirSync(OUT, { recursive: true });
    cpSync(tmp, OUT, { recursive: true });
    console.log(`wrote ${String(snapshot(OUT).size)} files to packages/sdk/src/wit/generated`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}
