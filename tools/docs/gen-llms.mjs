/**
 * Build every output file's contents.
 *
 * @returns {Record<string, string>} Filename to contents.
 */
export function buildAll() {
  const cfg = JSON.parse(read('tools/docs/bundles.json'));
  /** @type {Record<string, string>} */
  const out = {};

  const intro = preamble();
  const pointers = TOPICS.map((t) => t.pointer).join('\n');

  out['llms-full.txt'] =
    `${intro}# Generated by tools/docs/gen-llms.mjs. Do not edit.\n\n${pointers}\n\n` +
    concatFiles(corpusFiles());
  for (const topic of TOPICS) {
    out[topic.output] =
      `# ${topic.title}\n# ${topic.summary}\n` +
      `# Generated by tools/docs/gen-llms.mjs. Do not edit.\n\n${intro}${concatFiles(topic.files())}`;
  }
  out['llms.txt'] = buildIndex();

  for (const [name, spec] of Object.entries(cfg.bundles)) {
    const missing = spec.files.filter((f) => !exists(f));
    if (missing.length > 0) {
      throw new Error(`bundles.json: ${name} lists missing files: ${missing.join(', ')}`);
    }
    // A standalone bundle is for someone outside the engine (an app that only uses one package):
    // the engine's how-to-build-a-game preamble would send them the wrong way. A bundle with a
    // `preamble` of its own (the visit template's) opens with that instead.
    const opening = Array.isArray(spec.preamble) ? `${spec.preamble.join('\n')}\n` : intro;
    out[name] =
      `# ${spec.title}\n# ${spec.summary}\n# Generated by tools/docs/gen-llms.mjs. Do not edit.\n\n` +
      (spec.standalone === true ? standaloneFiles(spec.files) : opening + concatFiles(spec.files));
  }

  for (const name of OUTPUTS) {
    if (!(name in out)) throw new Error(`gen-llms: expected to produce ${name}`);
  }
  return out;
}

/**
 * Generate every bundle into `outDir` and enforce the size budgets.
 *
 * @param {string} outDir Absolute directory to write into.
 * @returns {{ name: string, bytes: number, budget: number }[]} Per-file sizes.
 */
export function generate(outDir) {
  mkdirSync(outDir, { recursive: true });
  const built = buildAll();
  /** @type {{ name: string, bytes: number, budget: number }[]} */
  const report = [];
  /** @type {string[]} */
  const over = [];

  for (const [name, text] of Object.entries(built)) {
    const target = join(outDir, name);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text, 'utf8');
    const bytes = Buffer.byteLength(text, 'utf8');
    const budget = BUDGETS[name] ?? Infinity;
    report.push({ name, bytes, budget });
    if (bytes > budget) {
      over.push(`${name}: ${fmt(bytes)} exceeds the ${fmt(budget)} budget`);
    }
  }

  if (over.length > 0) {
    throw new Error(
      `documentation size budget exceeded:\n  - ${over.join('\n  - ')}\n\n${largestCorpusFiles()}`,
    );
  }
  return report;
}

/**
 * The bundles that are nearly full: so the next routing decision is made in a planned step,
 * not by whoever's unrelated one-line edit hits the wall.
 *
 * @param {{ name: string, bytes: number, budget: number }[]} report `generate`'s sizes.
 * @returns {string[]} One warning per bundle with less than {@link HEADROOM_WARNING} of its
 *   budget left (an over-budget bundle is `generate`'s error, not a warning).
 */
export function headroomWarnings(report) {
  return report
    .filter((r) => r.bytes <= r.budget && r.budget - r.bytes < r.budget * HEADROOM_WARNING)
    .map(
      (r) =>
        `${r.name} has ${fmt(r.budget - r.bytes)} left of its ${fmt(r.budget)} budget, under ` +
        `${String(HEADROOM_WARNING * 100)}%: route a topic out (tools/docs/llms/topics.mjs) or trim`,
    );
}

/**
 * The ten largest files in the corpus, as a hint for whoever has to make room.
 * A budget failure is useless without knowing what is eating the budget.
 *
 * @returns {string} A formatted list.
 */
function largestCorpusFiles() {
  const rows = corpusFiles()
    .map((f) => ({ f, bytes: Buffer.byteLength(read(f), 'utf8') }))
    .sort((a, b) => b.bytes - a.bytes)
    .slice(0, 10);
  return [
    'The ten largest files in the corpus:',
    ...rows.map((r) => `  ${fmt(r.bytes).padStart(9)}  ${r.f}`),
  ].join('\n');
}

/**
 * Parse `--out <dir>` from an argv slice.
 *
 * @param {string[]} argv Arguments after the script name.
 * @returns {string} Absolute output directory.
 */
function parseArgs(argv) {
  const i = argv.indexOf('--out');
  if (i === -1) return ROOT;
  const v = argv[i + 1];
  if (!v) throw new Error('--out requires a directory');
  return v;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const outDir = parseArgs(process.argv.slice(2));
    const report = generate(outDir);
    const files = corpusFiles().length;
    console.log(`docs:llms — ${String(files)} source files -> ${outDir}`);
    for (const r of report) {
      console.log(`  ${r.name.padEnd(22)} ${fmt(r.bytes).padStart(9)}  (budget ${fmt(r.budget)})`);
    }
  } catch (err) {
    console.error(`docs:llms failed: ${err instanceof Error ? err.message : String(err)}`);
    process.exit(1);
  }
}
