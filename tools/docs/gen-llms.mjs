#!/usr/bin/env node
/**
 * Generates the committed documentation bundles:
 *
 * - `llms-full.txt`         the core corpus, in a fixed order, under its budget below; the topic
 *   bundles' pages are not in it, it carries one pointer line per topic instead
 * - `llms.txt`              a spec-style index, 4 KB cap
 * - `llms-fps.txt`          task bundle, file list from `bundles.json`
 * - `llms-third-person.txt` task bundle, file list from `bundles.json`
 * - `llms-three-character.txt` standalone bundle (no engine preamble): a studio character in
 *   any three.js app, for someone who uses only `@gameable/gameable-character`
 * - `llms-visit.txt`        task bundle, file list from `bundles.json`
 * - `llms-multiplayer.txt`  topic bundle: rooms and Play Solo (`llms/topics.mjs`)
 * - `llms-character.txt`    topic bundle: splat characters in a game (`llms/topics.mjs`)
 * - `llms-mystery.txt`      kit bundle: the mystery template (`llms/topics.mjs`)
 *
 * The pieces live in `tools/docs/llms/`: `files.mjs` (reading and concatenating), `topics.mjs`
 * (which pages each topic bundle takes out of the core corpus), `corpus.mjs` (the core corpus
 * and the preamble) and `indexFile.mjs` (`llms.txt`).
 *
 * Usage: `node tools/docs/gen-llms.mjs [--out <dir>]`
 *
 * `--out` exists so `tools/docs/lint.mjs` can regenerate into a temporary
 * directory and diff against the committed files. Do not edit the outputs by
 * hand; edit the docs and rerun.
 */
